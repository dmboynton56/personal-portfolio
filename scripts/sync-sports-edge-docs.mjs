#!/usr/bin/env node
/**
 * Sync Sports Edge freshness docs and KPI fallback from upstream dashboard artifacts.
 * Updates only machine-owned regions (marker blocks or fully generated sync-state.md).
 */
import fs from 'fs/promises'
import path from 'path'
import { fileURLToPath } from 'url'
import { createHash } from 'crypto'
import { createClient } from '@supabase/supabase-js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')

const UPSTREAM = {
  repo: 'dmboynton56/sports-edge',
  branch: 'main',
  performanceHistory:
    'https://raw.githubusercontent.com/dmboynton56/sports-edge/main/web/public/data/performance_history.json',
  pgaCurrent:
    'https://raw.githubusercontent.com/dmboynton56/sports-edge/main/web/public/data/pga_tournaments/current.json',
  cacheListing:
    'https://api.github.com/repos/dmboynton56/sports-edge/contents/data-core/notebooks/cache',
}

const PATHS = {
  syncState: path.join(root, 'docs/project-knowledge/sports-edge/sync-state.md'),
  evidenceRegister: path.join(root, 'docs/project-knowledge/evidence-register.md'),
  fallbackMetrics: path.join(root, 'public/data/project_metrics_fallback.json'),
}

async function fetchJson(url, label) {
  const res = await fetch(url, {
    headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'personal-portfolio-sync' },
  })
  if (!res.ok) {
    throw new Error(`Failed to fetch ${label} (${url}): ${res.status} ${res.statusText}`)
  }
  return res.json()
}

async function fetchLatestPgaMeta() {
  const listing = await fetchJson(UPSTREAM.cacheListing, 'PGA cache listing')
  const metaFiles = listing
    .filter(
      (entry) =>
        entry.type === 'file' &&
        entry.name.endsWith('_predictions.meta.json') &&
        !entry.name.includes('midtournament')
    )
    .sort((a, b) => b.name.localeCompare(a.name))

  if (metaFiles.length === 0) {
    throw new Error('No *_predictions.meta.json files found in sports-edge cache')
  }

  const latest = metaFiles[0]
  const meta = await fetchJson(latest.download_url, latest.name)
  return { meta, fileName: latest.name }
}

async function fetchSupabaseFreshness() {
  const url = process.env.SUPABASE_URL
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!url || !key) return null

  const supabase = createClient(url, key)
  const leagues = ['NBA', 'NFL', 'MLB']
  const rows = []

  for (const league of leagues) {
    const { data, error } = await supabase
      .from('predictions')
      .select('model_version, asof_ts')
      .eq('league', league)
      .order('asof_ts', { ascending: false })
      .limit(1)

    if (error) {
      console.warn(`Supabase ${league} freshness query failed:`, error.message)
      continue
    }
    if (data?.[0]) {
      rows.push({ league, ...data[0] })
    }
  }

  return rows.length > 0 ? rows : null
}

function summarizePerformanceHistory(performanceHistory) {
  const records = performanceHistory.records ?? []
  return records.map((record) => ({
    sport: record.sport,
    modelVersion: record.modelVersion,
    season: record.season,
    market: record.market,
    sampleSize: record.sampleSize,
    generatedAt: performanceHistory.generatedAt,
  }))
}

function computeFingerprint({ performanceHistory, pgaMeta, pgaMetaFile, pgaCurrent, supabaseFreshness }) {
  const payload = {
    perf: performanceHistory.generatedAt,
    pgaMetaFile,
    pgaMeta: {
      as_of: pgaMeta?.as_of ?? pgaMeta?.generated_at,
      n_sims: pgaMeta?.n_sims,
      n_players: pgaMeta?.n_players ?? pgaMeta?.field_size,
      model_version: pgaMeta?.model_version,
    },
    pgaCurrent: {
      generatedAt: pgaCurrent?.generatedAt,
      eventKey: pgaCurrent?.event?.eventKey,
      status: pgaCurrent?.event?.status,
    },
    supabase: supabaseFreshness,
    perfRecords: summarizePerformanceHistory(performanceHistory),
  }
  return createHash('sha256').update(JSON.stringify(payload)).digest('hex')
}

function readExistingFingerprint(syncStateContent) {
  const match = syncStateContent?.match(/^sync_fingerprint:\s*([a-f0-9]+)\s*$/m)
  return match?.[1] ?? null
}

function buildSyncStateMarkdown({ syncedAt, fingerprint, performanceHistory, pgaMeta, pgaCurrent, pgaMetaFile, supabaseFreshness, payload }) {
  const perfSummary = summarizePerformanceHistory(performanceHistory)
  const event = pgaCurrent?.event
  const meta = pgaMeta

  const lines = [
    '---',
    'project: sports-edge',
    `last_verified: ${syncedAt.slice(0, 10)}`,
    'role: auto_synced_live_state',
    `sync_fingerprint: ${fingerprint}`,
    'source_paths:',
    '  - https://github.com/dmboynton56/sports-edge/tree/main/web/public/data',
    '  - scripts/sync-sports-edge-docs.mjs',
    '---',
    '',
    '# Sports Edge Live Sync State',
    '',
    `_Auto-generated by \`scripts/sync-sports-edge-docs.mjs\` on ${syncedAt}. Do not edit manually._`,
    '',
    '## Sync metadata',
    '',
    `- **Upstream trigger:** ${payload?.source ?? 'manual/cron'}`,
    `- **Upstream run id:** ${payload?.run_id ?? 'n/a'}`,
    `- **Performance history generatedAt:** ${performanceHistory.generatedAt ?? 'unknown'}`,
    '',
    '## Ops dashboard',
    '',
    '- **URL:** https://sports-edge.drewboynton.com',
    '- **Portfolio embed:** `/api/sports-edges` + homepage Sports Edge card',
    '',
    '## Current PGA event',
    '',
  ]

  if (event) {
    lines.push(
      `- **Event:** ${event.name ?? event.eventKey ?? 'unknown'}`,
      `- **Status:** ${event.status ?? 'unknown'}`,
      `- **Dashboard generatedAt:** ${pgaCurrent.generatedAt ?? 'unknown'}`
    )
  } else {
    lines.push('- Event metadata unavailable from upstream current.json')
  }

  lines.push('', '## Latest PGA prediction meta', '')
  if (meta) {
    lines.push(
      `- **Artifact:** \`${pgaMetaFile}\``,
      `- **As of:** ${meta.as_of ?? meta.generated_at ?? 'unknown'}`,
      `- **Field size:** ${meta.n_players ?? meta.field_size ?? 'unknown'} players`,
      `- **Simulations:** ${meta.n_sims ?? 'unknown'}`,
      `- **Model version:** ${meta.model_version ?? 'unknown'}`
    )
  }

  lines.push('', '## Cross-league performance history', '')
  if (perfSummary.length === 0) {
    lines.push('_No performance history records found._')
  } else {
    lines.push('| Sport | Model | Season | Market | Sample |', '| --- | --- | --- | --- | --- |')
    for (const row of perfSummary) {
      lines.push(
        `| ${row.sport} | ${row.modelVersion ?? '—'} | ${row.season ?? '—'} | ${row.market ?? '—'} | ${row.sampleSize ?? '—'} |`
      )
    }
  }

  if (supabaseFreshness?.length) {
    lines.push('', '## Supabase serving freshness', '')
    lines.push('| League | Model version | As of (UTC) |', '| --- | --- | --- |')
    for (const row of supabaseFreshness) {
      lines.push(`| ${row.league} | ${row.model_version ?? '—'} | ${row.asof_ts ?? '—'} |`)
    }
  }

  lines.push('')
  return lines.join('\n')
}

function buildDerivedEvidenceRows({ syncedAt, performanceHistory, pgaMeta, pgaMetaFile, pgaCurrent }) {
  const event = pgaCurrent?.event
  const rows = [
    `| derived | Performance history generatedAt | ${performanceHistory.generatedAt ?? 'unknown'} | sports-edge/web/public/data/performance_history.json | Synced ${syncedAt.slice(0, 10)}. |`,
  ]

  if (pgaMeta) {
    rows.push(
      `| derived | Latest PGA meta artifact | ${pgaMetaFile} | sports-edge/data-core/notebooks/cache/${pgaMetaFile} | ${pgaMeta.n_sims ?? '?'} sims, ${pgaMeta.n_players ?? pgaMeta.field_size ?? '?'} players, as-of ${pgaMeta.as_of ?? pgaMeta.generated_at ?? 'unknown'}. |`
    )
  }

  if (event) {
    rows.push(
      `| derived | Current PGA dashboard event | ${event.name ?? event.eventKey} (${event.status ?? 'unknown'}) | sports-edge/web/public/data/pga_tournaments/current.json | generatedAt ${pgaCurrent.generatedAt ?? 'unknown'}. |`
    )
  }

  return rows.join('\n')
}

function buildFallbackMetrics({ syncedAt, pgaMeta, pgaCurrent }) {
  const event = pgaCurrent?.event
  const pgaLabel = event?.name ? `${event.name.split(' ')[0]} PGA` : 'PGA active'
  const sims = pgaMeta?.n_sims ? pgaMeta.n_sims.toLocaleString('en-US') : '—'
  const field = pgaMeta?.n_players ?? pgaMeta?.field_size

  return {
    generatedAt: syncedAt,
    metrics: [
      { label: 'League Coverage', value: 'NBA • NFL • MLB • PGA • CBB • WC', iconName: 'workflow' },
      { label: 'Ops Dashboard', value: 'sports-edge.drewboynton.com', iconName: 'activity' },
      { label: pgaLabel, value: field ? `${field} players • ${sims} sims` : sims, iconName: 'database' },
      { label: 'Refresh Cadence', value: '13:00 UTC daily', iconName: 'clock' },
    ],
  }
}

function replaceMarkerBlock(content, markerId, inner) {
  const begin = `<!-- BEGIN SYNC:${markerId} -->`
  const end = `<!-- END SYNC:${markerId} -->`
  const pattern = new RegExp(`${begin}[\\s\\S]*?${end}`)
  const replacement = `${begin}\n${inner}\n${end}`
  if (!pattern.test(content)) {
    throw new Error(`Marker block SYNC:${markerId} not found`)
  }
  return content.replace(pattern, replacement)
}

async function writeIfChanged(filePath, nextContent) {
  let previous = null
  try {
    previous = await fs.readFile(filePath, 'utf8')
  } catch {
    // new file
  }
  if (previous === nextContent) {
    return false
  }
  await fs.mkdir(path.dirname(filePath), { recursive: true })
  await fs.writeFile(filePath, nextContent, 'utf8')
  return true
}

async function main() {
  const syncedAt = new Date().toISOString()
  const payload = {
    source: process.env.SYNC_SOURCE ?? 'manual',
    run_id: process.env.SYNC_RUN_ID ?? '',
  }

  console.log('Fetching upstream Sports Edge artifacts...')
  const [performanceHistory, pgaCurrent, { meta: pgaMeta, fileName: pgaMetaFile }] =
    await Promise.all([
      fetchJson(UPSTREAM.performanceHistory, 'performance_history.json'),
      fetchJson(UPSTREAM.pgaCurrent, 'pga_tournaments/current.json'),
      fetchLatestPgaMeta(),
    ])

  const supabaseFreshness = await fetchSupabaseFreshness()

  const fingerprint = computeFingerprint({
    performanceHistory,
    pgaMeta,
    pgaMetaFile,
    pgaCurrent,
    supabaseFreshness,
  })

  let existingSyncState = null
  try {
    existingSyncState = await fs.readFile(PATHS.syncState, 'utf8')
  } catch {
    // first run
  }

  if (readExistingFingerprint(existingSyncState) === fingerprint) {
    console.log('Upstream fingerprint unchanged; skipping doc sync.')
    return
  }

  const syncStateMd = buildSyncStateMarkdown({
    syncedAt,
    fingerprint,
    performanceHistory,
    pgaMeta,
    pgaCurrent,
    pgaMetaFile,
    supabaseFreshness,
    payload,
  })

  const derivedRows = buildDerivedEvidenceRows({
    syncedAt,
    performanceHistory,
    pgaMeta,
    pgaMetaFile,
    pgaCurrent,
  })

  const evidenceContent = await fs.readFile(PATHS.evidenceRegister, 'utf8')
  const nextEvidence = replaceMarkerBlock(evidenceContent, 'sports-edge-derived', derivedRows)

  const fallbackRaw = await fs.readFile(PATHS.fallbackMetrics, 'utf8')
  const fallback = JSON.parse(fallbackRaw)
  fallback['sports-edge'] = buildFallbackMetrics({ syncedAt, pgaMeta, pgaCurrent })
  const nextFallback = `${JSON.stringify(fallback, null, 4)}\n`

  const changes = []
  if (await writeIfChanged(PATHS.syncState, syncStateMd)) changes.push(PATHS.syncState)
  if (await writeIfChanged(PATHS.evidenceRegister, nextEvidence)) changes.push(PATHS.evidenceRegister)
  if (await writeIfChanged(PATHS.fallbackMetrics, nextFallback)) changes.push(PATHS.fallbackMetrics)

  if (changes.length === 0) {
    console.log('No changes detected; upstream artifacts match current portfolio docs.')
    return
  }

  console.log(`Updated ${changes.length} file(s):`)
  for (const file of changes) {
    console.log(`  - ${path.relative(root, file)}`)
  }
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
